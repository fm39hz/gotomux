// Package identity creates and validates gotomux logical object IDs.
package identity

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"strings"
)

// New returns a canonical lowercase UUIDv4 suitable for persistence in a
// baseline and in a tmux user option.
func New() (string, error) {
	var raw [16]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return "", fmt.Errorf("generate logical identity: %w", err)
	}
	raw[6] = raw[6]&0x0f | 0x40
	raw[8] = raw[8]&0x3f | 0x80
	encoded := hex.EncodeToString(raw[:])
	return encoded[:8] + "-" + encoded[8:12] + "-" + encoded[12:16] + "-" + encoded[16:20] + "-" + encoded[20:], nil
}

// Validate accepts only canonical lowercase UUIDv4 values generated by New.
func Validate(id string) error {
	if len(id) != 36 || id[8] != '-' || id[13] != '-' || id[18] != '-' || id[23] != '-' || strings.ToLower(id) != id {
		return fmt.Errorf("logical identity is not a canonical UUID")
	}
	compact := strings.ReplaceAll(id, "-", "")
	raw, err := hex.DecodeString(compact)
	if err != nil || len(raw) != 16 {
		return fmt.Errorf("logical identity is not a canonical UUID")
	}
	if id[14] != '4' || !strings.ContainsRune("89ab", rune(id[19])) {
		return fmt.Errorf("logical identity must be UUIDv4")
	}
	return nil
}
